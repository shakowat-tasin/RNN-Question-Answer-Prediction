def tokenize(text):
  #lower
  text=text.lower()

  #remove quotes

  text=re.sub(r"[\"']","",text)
  text = re.sub(r"[^a-z0-9\s]", " ", text)
  text = re.sub(r"\s+", " ", text).strip()
  token=text.split()




  return token

