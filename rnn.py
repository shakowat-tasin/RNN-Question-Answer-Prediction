import torch
from torch.utils.data import Dataset,DataLoader

class QAdatset(Dataset):


  def __init__(self,df,vocab):
    self.df=df
    self.vocab=vocab



  def __len__(self):
    return self.df.shape[0]

  def __getitem__(self,index):
    numeric_question=text_to_indices(self.df.iloc[index][0],self.vocab)
    numeric_ans=text_to_indices(self.df.iloc[index]['answer'],self.vocab)


    return torch.tensor(numeric_question),torch.tensor(numeric_ans)

